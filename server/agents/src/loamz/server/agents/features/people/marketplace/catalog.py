def _bundle(
    id: str,
    name: str,
    tagline: str,
    description: str,
    icon: str,
    category: str,
    includes: list[str],
    seen: list[str],
) -> Listing:
    return Listing(
        id=id,
        kind="plugin",
        name=name,
        tagline=tagline,
        description=description,
        icon=icon,
        category=category,
        includes=includes,
        data_seen_by=seen,
        added_at="2026-10-28",
    )


